def _行を読む() -> list[dict]:
    if 置き場.exists():
        text = 置き場.read_text(encoding="utf-8")
    elif not リストのURL:
        print(f"::warning::{置き場} がありません。今日はふるさと納税を紹介しません。")
        return []
    else:
        try:
            req = urllib.request.Request(リストのURL, headers={"User-Agent": "compose"})
            with urllib.request.urlopen(req, timeout=30) as res:
                text = res.read().decode("utf-8")
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            print(f"::warning::ふるさと納税のリストを読めませんでした（{exc}）。今日は紹介しません。")
            return []
    出 = []
    for 行 in text.splitlines():
        行 = 行.strip()
        if not 行 or 行.startswith("#"):
            continue
        try:
            x = json.loads(行)
        except json.JSONDecodeError:
            continue
        if not (x.get("url") and x.get("名")):
            continue
        # 石川：表示用の「名」に「災害・復興・支援・応援・被災」がある品は紹介しない。
        # 楽天の元の商品名（生の名）で判じると、「能登半島地震復興支援」の札が付いた
        # 能登の返礼品がほぼ全部落ちる（2026-10-09 運用部・石川担当）。札は 見せる名 で落とす。
        if 名で外す語 and re.search(名で外す語, str(x["名"])):
            continue
        出.append(x)
    return 出


