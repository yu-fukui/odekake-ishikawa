def _避ける日か(切り口: dict, 対象日: date) -> bool:
    """切り口の「避ける日」（"01-01" の形）の前後「前後」日なら True。"""
    幅 = int(切り口.get("前後", 0))
    for md in 切り口.get("避ける日", []):
        月, 日 = (int(v) for v in md.split("-"))
        for 年 in (対象日.year - 1, 対象日.year, 対象日.year + 1):
            if abs((対象日 - date(年, 月, 日)).days) <= 幅:
                return True
    return False


