def _中身がある(s: str) -> bool:
    """【…】を全部取ってもまだ言葉が残るか。宣伝文句だけの行を防ぐ。"""
    return len(re.sub(r"【[^】]*】", "", s).strip(" \u3000・、/／")) >= 4


def _括弧の外の区切り(s: str) -> int:
    """【…】の外にある「／ 」「/ 」の位置。検索語の羅列がそこから始まる。

    括弧の中の「令和8年産 / 令和9年産」や、数量の「5kg/10kg」で切らないように、
    括弧の深さを数えながら探す。
    """
    深さ = 0
    for i, c in enumerate(s):
        if c in "【（(「《":
            深さ += 1
        elif c in "】）)」》":
            深さ = max(0, 深さ - 1)
        elif 深さ == 0 and c in "／/" and i > 12:
            前 = s[i - 1]
            後 = s[i + 1:i + 2]
            # 「5kg/10kg」のように前後が詰まっているものは数量なので切らない
            if 前 in " \u3000" or 後 in (" ", "\u3000"):
                return i
    return -1


def 見せる名(品: dict, 上限: int = 50) -> str:
    """楽天の商品名を、読める長さに整える。

    2026-09-25、代表の指示で「短く言い換えた名前」から「元のタイトルの頭」に変えた。
      > ふるさと納税の1投稿目に価格はいらないと思います。素直にタイトルではだめ？
    元のタイトルは中央128字あり、7件並べると入らない。なので頭だけを使う。

    落とすもの:
      - 枠の名前と重なる「【ふるさと納税】」
      - 「[A-013010]」のような商品コード
      - 「｜」「／ 」より後ろの検索語の羅列（楽天の商品名はここから先が飾り）
    切るときは【…】の切れ目を優先する。宣伝文句だけが残る切り方はしない。
    """
    s = str(品.get("生の名") or 品.get("名") or "")
    s = s.replace("【ふるさと納税】", " ")
    if 写さない札:
        # 「【能登半島地震復興支援】」のような札は投稿・返信に写さない（石川）。
        # 括弧ごと落とし、それでも語が残るなら表示用の「名」を使う
        s = re.sub(r"[【\[［（(《][^】\]］）)》]*(?:" + 写さない札 + r")[^】\]］）)》]*[】\]］）)》]", " ", s)
        if re.search(写さない札, s):
            s = str(品.get("名") or "")
            if re.search(写さない札, s):
                s = re.sub(写さない札, " ", s)
    s = re.sub(r"\[[A-Za-z0-9\-_]{3,}\]", " ", s)
    s = re.sub(r"^\s*[《＼\\][^》]{0,40}》\s*", " ", s)
    s = re.sub(r"^[\s\u3000]*[》】\]）)／/｜|]+", " ", s)
    # 「お届け：寄附確認後、順次出荷…」のような配送の案内は名前ではないので、そこから先を落とす
    s = re.split(r"\s(?:お届け|発送|配送)(?:時期)?[：:]", s)[0]
    # 「｜」だけでなく、区切りに使われた半角の l・I もここで切る
    s = re.split(r"[｜|]|(?<=[\s\u3000])[lI](?=[\s\u3000])", s)[0]
    i = _括弧の外の区切り(s)
    if i > 0:
        s = s[:i]
    s = re.sub(r"[\u3000\s]+", " ", s).strip(" \u3000・、/／")
    s = _飾りを落とす(s)

    if len(s) <= 上限:
        return _とじる(s)
    切 = s[:上限 + 1]
    閉 = 切.rfind("】")
    if 閉 >= 上限 // 2 and _中身がある(切[:閉 + 1]):
        return _とじる(切[:閉 + 1])
    空 = 切.rfind(" ")
    切 = 切[:空] if 空 >= 上限 // 2 else s[:上限]
    return _とじる(切)


# 一覧の名前の目安（2026-10-09 運用部・石川担当「品の名前だけ（目安30字）にしてもらえると読みやすい」）
名前の目安 = 32


def _飾りを落とす(s: str) -> str:
    """楽天の検索向けの飾りを落として、品の名前だけにする。

    例「★5.00 高評価★ 【和牛セレブ】 能登牛 切り落とし ( 選べる内容量 : 200g … )」→「能登牛 切り落とし」
      - ★〜★、「高評価」
      - 頭の【…】＜…＞（宣伝の札。後ろに名前が続くときだけ）
      - （選べる…）
      - 県名から先（「石川県 能登 穴水町 年内発送 黒毛和牛…」のような検索語の並び）
      - それでも長ければ、目安の字数の手前の空白で切る
    """
    元 = s
    s = re.sub(r"★[^★]{0,30}★", " ", s)
    s = re.sub(r"(?:\d\.\d+\s*)?高評価", " ", s)
    s = re.sub(r"★\s*\d\.\d+", " ", s)
    # 宣伝の【…】（冷蔵・指定日着可・数量限定など）は、どこにあっても落とす
    s = re.sub(r"【[^】]{0,30}(?:冷蔵|冷凍|指定日|送料|無料|限定|発送|配送|楽天|ランキング|直送|最短|お届け|予約|受賞|高評価)[^】]{0,30}】", " ", s)
    s = re.sub(r"^\s*選べる[^\s【［（(<＜]{0,6}\s*", " ", s)
    s = re.sub(r"[(（][^()（）]*選べる[^()（）]*[)）]", " ", s)
    s = re.sub(r"[\u3000\s]+", " ", s).strip(" \u3000・、/／")
    while True:
        m = re.match(r"^(?:【[^】]{0,30}】|＜[^＞]{0,30}＞|<[^>]{0,30}>|［[^］]{0,30}］)\s*", s)
        if not m or len(s) - m.end() < 6:
            break
        s = s[m.end():]
    m = re.search(r"[\s/／]+[［\[]?" + re.escape(県名) + r"(?:県|産|県産)?", s)
    if m and m.start() >= 12:
        s = s[:m.start()]
    s = s.strip(" \u3000・、/／")
    if len(s) > 名前の目安:
        空 = s.rfind(" ", 0, 名前の目安 + 1)
        頭 = s[:空]
        # 『…』「…」（…）の途中では切らない（「『Sabae Tsumekiri…』」が「『Sabae」になる）
        閉じている = all(頭.count(開) == 頭.count(閉) for 開, 閉 in (("『", "』"), ("「", "」"), ("（", "）"), ("(", ")")))
        if 空 >= 10 and 閉じている:
            s = 頭
    s = _とじる(s.strip(" \u3000・、/／"))
    return s if len(s) >= 4 else 元


def _とじる(s: str) -> str:
    """切った拍子に開いたままになった括弧を落とす。"""
    for 開, 閉 in (("【", "】"), ("（", "）"), ("(", ")"), ("「", "」"), ("《", "》")):
        while s.count(開) > s.count(閉):
            i = s.rfind(開)
            if i < 0:
                break
            s = (s[:i] + s[i + 1:]).strip(" 　・、")
        while s.count(閉) > s.count(開):
            i = s.rfind(閉)
            if i < 0:
                break
            s = (s[:i] + s[i + 1:]).strip(" 　・、")
    return s


